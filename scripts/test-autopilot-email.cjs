// ── Main ─────────────────────────────────────────────────────────────────────

async function main() {
    console.log('[Test] Starting analysis-only autopilot test for user', USER_ID);

    // 1. Load user from DB
    const user = await new Promise((ok, fail) =>
        db.get('SELECT id, displayname, email, fpl_entry_id, fpl_session, fpl_refresh_token, fpl_expires_at, credits, manager_dna FROM users WHERE id = ?',
            [USER_ID], (err, row) => err ? fail(err) : ok(row)));
    if (!user) throw new Error('User not found');
    console.log(`[Test] User: ${user.displayname}, entry: ${user.fpl_entry_id}, credits: ${user.credits}`);

    // 2. Get FPL token
    const fplToken = await getValidFplToken(user.id, user);
    if (!fplToken) throw new Error('No valid FPL token — user needs to reconnect via the extension');
    const fplHeaders = {
        'Authorization': `Bearer ${fplToken}`,
        'Content-Type': 'application/json',
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
        'Accept': 'application/json',
        'Origin': 'https://fantasy.premierleague.com',
        'Referer': 'https://fantasy.premierleague.com/',
    };

    // 3. Fetch bootstrap + team data in parallel
    console.log('[Test] Fetching FPL data...');
    const [bootstrapRes, teamRes, entryRes, historyRes, transfersRes] = await Promise.all([
        fetch('https://fantasy.premierleague.com/api/bootstrap-static/'),
        fetch(`https://fantasy.premierleague.com/api/my-team/${user.fpl_entry_id}/`, { headers: fplHeaders }),
        fetch(`https://fantasy.premierleague.com/api/entry/${user.fpl_entry_id}/`),
        fetch(`https://fantasy.premierleague.com/api/entry/${user.fpl_entry_id}/history/`),
        fetch(`https://fantasy.premierleague.com/api/entry/${user.fpl_entry_id}/transfers/`),
    ]);

    if (!teamRes.ok) throw new Error(`my-team fetch failed: ${teamRes.status} — FPL session may have expired`);
    const [bootstrapData, teamData, entryData, historyData, transfersData] = await Promise.all([
        bootstrapRes.json(), teamRes.json(), entryRes.json(), historyRes.json(), transfersRes.json(),
    ]);

    // 4. Determine current GW
    const nextEvent = bootstrapData.events?.find(e => !e.finished && e.is_next) || bootstrapData.events?.find(e => !e.finished) || bootstrapData.events?.[bootstrapData.events.length - 1];
    const nextGw = nextEvent?.id ?? 38;
    console.log(`[Test] Target GW: ${nextGw}`);

    // 5. Fetch fixtures for next 4 GWs
    const fixtureGws = [nextGw, nextGw + 1, nextGw + 2, nextGw + 3].filter(gw => gw <= 38);
    const fixtureArrays = await Promise.all(
        fixtureGws.map(gw => fetch(`https://fantasy.premierleague.com/api/fixtures/?event=${gw}`)
            .then(r => r.json()).then(data => (Array.isArray(data) ? data : []).map(f => ({ ...f, event: gw }))).catch(() => []))
    );
    const fixtures = fixtureArrays.flat();

    // 6. Build picks/history context
    const picksData = {
        picks: teamData.picks || [],
        active_chip: teamData.transfers?.active_chip ?? null,
        entry_history: (() => {
            const latest = historyData?.current?.[historyData.current.length - 1];
            return latest
                ? { event: latest.event, overall_rank: latest.overall_rank, total_points: latest.total_points, points: latest.points }
                : { event: nextGw - 1, overall_rank: 0, total_points: 0, points: 0 };
        })(),
    };
    const transfersAvailable = Math.max(0, (teamData.transfers?.limit ?? 1) - (teamData.transfers?.made ?? 0));
    const usedChipNames = (historyData?.chips || []).map(c => c.name);
    const wcEvents = (historyData?.chips || []).filter(c => c.name === 'wildcard').map(c => c.event);
    const secondHalfWcUsed = wcEvents.some(e => e > 20);
    const firstHalfWcUsed = wcEvents.some(e => e <= 20);
    const wildcardAvailable = nextGw <= 20 ? !firstHalfWcUsed : !secondHalfWcUsed;
    const availableChips = ['wildcard', 'freehit', 'bboost', '3xc'].filter(c => {
        if (c === 'wildcard') return wildcardAvailable;
        return !usedChipNames.includes(c);
    });
    const recentTransferHistory = Array.isArray(transfersData) ? transfersData.slice(0, 12) : [];

    // 7. Build prompt — load from server.cjs at runtime
    // We require the server module's buildServerWolfPrompt via a thin eval trick —
    // instead, we inline a minimal prompt builder that calls the real one via the running server,
    // or we duplicate the call. Since server.cjs isn't a clean module, we use the /api/wolf-analysis
    // endpoint indirectly. Simpler: just re-implement the prompt call inline using the same AI call.
    console.log('[Test] Building prompt and calling AI...');

    // Load ARCHETYPE_DIRECTIVES and buildServerWolfPrompt by requiring a helper that exposes them
    // Since server.cjs exports nothing, we call the AI directly with a concise prompt fallback
    // and delegate full prompt building to the running server's /api/wolf-analysis endpoint.
    // ---- Actually, we call the AI directly here with the same logic ----

    // Minimal inline prompt builder (mirrors buildServerWolfPrompt in server.cjs)
    const players = bootstrapData.elements || [];
    const teams = bootstrapData.teams || [];
    const getPlayer = id => players.find(p => p.id === id);
    const getTeam = id => teams.find(t => t.id === id);

    const squadLines = (picksData.picks || []).map(pick => {
        const p = getPlayer(pick.element);
        if (!p) return null;
        const team = getTeam(p.team);
        const pos = ['', 'GK', 'DEF', 'MID', 'FWD'][p.element_type] || '?';
        const capFlag = pick.is_captain ? ' [C]' : pick.is_vice_captain ? ' [VC]' : '';
        return `${pos} ${p.web_name} (${team?.short_name}) £${(p.now_cost / 10).toFixed(1)}m — Form: ${p.form}, Pts: ${p.total_points}${capFlag} | Pos:${pick.position}`;
    }).filter(Boolean).join('\n');

    const fixtureLines = fixtures.slice(0, 40).map(f => {
        const h = getTeam(f.team_h), a = getTeam(f.team_a);
        return `GW${f.event}: ${h?.short_name ?? f.team_h} vs ${a?.short_name ?? f.team_a}`;
    }).join('\n');

    const prompt = `You are The Wolf, an expert FPL (Fantasy Premier League) analyst. Analyse the following squad for GW${nextGw} and provide a detailed recommendation.

SQUAD (${picksData.picks?.length ?? 0} players, ${transfersAvailable} free transfer(s)):
${squadLines}

AVAILABLE CHIPS: ${availableChips.join(', ') || 'none'}
ACTIVE CHIP: ${picksData.active_chip || 'none'}
MANAGER DNA: ${user.manager_dna || 'not set'}

UPCOMING FIXTURES (GW${nextGw}–${nextGw + 3}):
${fixtureLines}

SEASON HISTORY: GW${picksData.entry_history.event} — ${picksData.entry_history.total_points} pts total, rank ${picksData.entry_history.overall_rank?.toLocaleString() ?? 'N/A'}

Provide your analysis in this format:
## 🐺 THE WOLF'S VERDICT
[2-3 sentence overall assessment of the squad]

## 📋 THE PLAN
[Bullet-point recommended transfers, captain pick, and any chip advice]

## 🔍 DETAILED ANALYSIS
[Position-by-position breakdown with reasoning]

## ⚠️ RISKS & DIFFERENTIALS
[Key injury risks, price change flags, differential opportunities]

Be specific, opinionated, and concise. Name players directly.`;

    // 8. Call AI
    const aiProvider = (process.env.AI_PROVIDER || 'claude').toLowerCase();
    let analysisText;
    if (aiProvider === 'gemini') {
        const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
        if (!GEMINI_API_KEY) throw new Error('GEMINI_API_KEY not set');
        const gRes = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${GEMINI_API_KEY}`, {
            method: 'POST', headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }], generationConfig: { temperature: 0.7, maxOutputTokens: 16000 } }),
        });
        if (!gRes.ok) throw new Error(`Gemini error: ${gRes.status} — ${await gRes.text()}`);
        const gData = await gRes.json();
        analysisText = gData?.candidates?.[0]?.content?.parts?.[0]?.text ?? '';
    } else {
        const ANTHROPIC_API_KEY = process.env.ANTHROPIC_API_KEY;
        if (!ANTHROPIC_API_KEY) throw new Error('ANTHROPIC_API_KEY not set');
        const cRes = await fetch('https://api.anthropic.com/v1/messages', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json', 'x-api-key': ANTHROPIC_API_KEY, 'anthropic-version': '2023-06-01' },
            body: JSON.stringify({ model: 'claude-sonnet-4-6', max_tokens: 16000, temperature: 0.7, messages: [{ role: 'user', content: prompt }] }),
        });
        if (!cRes.ok) throw new Error(`Claude error: ${cRes.status} — ${await cRes.text()}`);
        const cData = await cRes.json();
        analysisText = cData?.content?.[0]?.text ?? '';
    }
    if (!analysisText) throw new Error('Empty AI response');
    console.log(`[Test] AI response received (${analysisText.length} chars)`);

    // 9. Generate PDF
    console.log('[Test] Generating PDF...');
    let pdfBuffer = null;
    try {
        pdfBuffer = await generateAnalysisPDF(analysisText, user.displayname, entryData.name, nextGw);
        console.log(`[Test] PDF generated (${pdfBuffer?.length} bytes)`);
    } catch (pdfErr) {
        console.warn('[Test] PDF generation failed:', pdfErr.message);
    }

    // 10. Send email (to override address, not user.email, for testing)
    console.log(`[Test] Sending email to ${OVERRIDE_EMAIL}...`);
    const emailResult = await sendEmail(OVERRIDE_EMAIL, user.displayname, entryData.name, nextGw, analysisText, pdfBuffer);
    console.log('[Test] Email sent:', JSON.stringify(emailResult));

    console.log('\n[Test] ✅ Done — analysis emailed, NO transfers were made.');
    process.exit(0);
}

main().catch(err => {
    console.error('[Test] Fatal error:', err.message);
    process.exit(1);
});
