async function refreshFplToken(userId, refreshToken) {
    const res = await fetch('https://users.premierleague.com/accounts/token/', {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
        body: new URLSearchParams({ grant_type: 'refresh_token', refresh_token: refreshToken }),
    });
    if (!res.ok) throw new Error(`Token refresh HTTP ${res.status}`);
    const data = await res.json();
    const newToken = data.access_token;
    const newRefresh = data.refresh_token || refreshToken;
    const expiresAt = data.expires_in ? Math.floor(Date.now() / 1000) + data.expires_in : null;
    await new Promise((ok, fail) =>
        db.run('UPDATE users SET fpl_session = ?, fpl_refresh_token = ?, fpl_expires_at = ? WHERE id = ?',
            [newToken, newRefresh, expiresAt, userId], err => err ? fail(err) : ok()));
    return newToken;
}

async function getValidFplToken(userId, row) {
    const nowSecs = Math.floor(Date.now() / 1000);
    const isExpired = row.fpl_expires_at && (row.fpl_expires_at - 60) < nowSecs;
    if (isExpired && row.fpl_refresh_token) {
        console.log(`[FPL] Token expired, refreshing...`);
        try { return await refreshFplToken(userId, row.fpl_refresh_token); }
        catch { console.warn('[FPL] Refresh failed'); return null; }
    }
    return row.fpl_session;
}

